// Regenerates functions/api/_kb.js from the KB + COUNTRIES arrays inside the chatbot HTML,
// so the LLM is grounded in exactly the same facts the rule-based bot uses.
// Usage: node chatbot/scripts/build-kb.cjs
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "gctb_nursing_ad_chat.html"), "utf8");
function grab(name){
  const start = html.indexOf(`const ${name} = [`);
  if(start < 0) throw new Error(name + " not found");
  let i = html.indexOf("[", start), depth = 0;
  for(; i < html.length; i++){ const c = html[i]; if(c==="[") depth++; else if(c==="]" && --depth===0) break; }
  return vm.runInNewContext("(" + html.slice(html.indexOf("[", start), i + 1) + ")");
}
const KB = grab("KB"), COUNTRIES = grab("COUNTRIES");
const SKIP = new Set(["ack","positive","robot","nervous","confused","interested","later","hindi","fromwhere","busy","help","rude","love","thanks","greet","howru","bye","b2done","who","call"]);
const strip = (s) => s.replace(/[\u{1F300}-\u{1FAFF}\u2600-\u27BF\uFE0F]/gu, "").replace(/\s+/g, " ").trim();
const facts = KB.filter(e => !SKIP.has(e.id)).map(e => ({ id: e.id, k: e.keywords, a: strip(e.a) }));
const countries = COUNTRIES.map(c => ({ k: c.k, name: c.name.en,
  text: `${c.name.en}: salary ${c.salary.en}; exam ${c.exam.en}; cost ${c.cost.en}; visa ${c.visa.en}; timeline ${c.time.en}` }));
const out = `// AUTO-GENERATED by chatbot/scripts/build-kb.cjs from gctb_nursing_ad_chat.html. Do not edit by hand.\n` +
  `export const KB_FACTS = ${JSON.stringify(facts, null, 0)};\nexport const COUNTRY_FACTS = ${JSON.stringify(countries, null, 0)};\n`;
fs.writeFileSync(path.join(root, "functions/api/_kb.js"), out);
console.log("wrote _kb.js:", facts.length, "facts,", countries.length, "countries");
